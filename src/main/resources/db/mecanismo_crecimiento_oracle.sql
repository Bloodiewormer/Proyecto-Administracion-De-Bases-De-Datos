-- EIF402 - Módulo 3. Oracle 21c XE.
-- Instalación: ejecutar como SYSTEM en XEPDB1, con CURRENT_SCHEMA = SYSTEM.
-- PRERREQUISITO: un usuario SYSDBA debe conectarse, cambiar a XEPDB1 y conceder
-- SELECT DIRECTO a SYSTEM sobre SYS.DBA_DATA_FILES, SYS.DBA_TEMP_FILES,
-- SYS.DBA_FREE_SPACE, SYS.DBA_TABLESPACES, SYS.V_$TEMP_SPACE_HEADER,
-- SYS.V_$DATABASE, SYS.V_$INSTANCE y SYS.V_$CONTAINERS.
-- Los ocho GRANT y los pasos exactos están en docs/modulo-3-almacenamiento.md.
-- No ejecutar esos GRANT como parte de este script ni instalar los objetos como SYS.
-- Después: conectar SYSTEM a XEPDB1, ejecutar este archivo y verificar objetos VALID
-- y JOB_HISTORIAL_ALMACENAMIENTO con ENABLED = FALSE. No habilitar el job.
-- No ejecutado automáticamente por la aplicación.
-- Se conservan las filas antiguas, pero no se les inventa una identidad ni se incluyen en la serie nueva.

BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE HISTORIAL_CRECIMIENTO_BD (
        ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
        FECHA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        BYTES_DATAFILES NUMBER NOT NULL, BYTES_TEMPFILES NUMBER NOT NULL,
        BYTES_REDO NUMBER, BYTES_USADOS NUMBER NOT NULL, BYTES_LIBRES NUMBER NOT NULL,
        CANTIDAD_TABLESPACES NUMBER, CANTIDAD_ARCHIVOS NUMBER)';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

-- Migración aditiva e idempotente: las columnas antiguas y sus datos se conservan.
DECLARE
    PROCEDURE AGREGAR(P_NOMBRE VARCHAR2, P_TIPO VARCHAR2) IS
        V_EXISTE NUMBER;
    BEGIN
        SELECT COUNT(*) INTO V_EXISTE FROM USER_TAB_COLUMNS
        WHERE TABLE_NAME = 'HISTORIAL_CRECIMIENTO_BD' AND COLUMN_NAME = P_NOMBRE;
        IF V_EXISTE = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE HISTORIAL_CRECIMIENTO_BD ADD (' || P_NOMBRE || ' ' || P_TIPO || ')';
        END IF;
    END;
BEGIN
    AGREGAR('DBID', 'NUMBER');
    AGREGAR('CON_DBID', 'NUMBER');
    AGREGAR('CON_ID', 'NUMBER');
    AGREGAR('INSTANCE_NAME', 'VARCHAR2(128)');
    AGREGAR('SERVICE_NAME', 'VARCHAR2(256)');
    AGREGAR('CON_NAME', 'VARCHAR2(128)');
    AGREGAR('ALCANCE', 'VARCHAR2(40)');
END;
/
-- BYTES_REDO es una columna heredada. No se utiliza para el total ni para la ocupación.
-- Las capturas nuevas no la rellenan: el redo tiene alcance de instancia, no de PDB.
DECLARE
    V_NULLABLE VARCHAR2(1);
BEGIN
    SELECT NULLABLE INTO V_NULLABLE FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'HISTORIAL_CRECIMIENTO_BD' AND COLUMN_NAME = 'BYTES_REDO';
    IF V_NULLABLE = 'N' THEN
        EXECUTE IMMEDIATE 'ALTER TABLE HISTORIAL_CRECIMIENTO_BD MODIFY (BYTES_REDO NULL)';
    END IF;
    EXECUTE IMMEDIATE 'ALTER TABLE HISTORIAL_CRECIMIENTO_BD MODIFY (BYTES_REDO DEFAULT NULL)';
END;
/

-- La misma definición de tablespaces que consulta la aplicación (incluye TEMP y UNDO).
CREATE OR REPLACE VIEW V_ALMACENAMIENTO_ACTUAL AS
WITH DATAFILES AS (
    SELECT TABLESPACE_NAME,
           SUM(BYTES) AS BYTES_TOTAL,
           SUM(CASE WHEN AUTOEXTENSIBLE = 'YES'
                    THEN GREATEST(BYTES, MAXBYTES) ELSE BYTES END) AS BYTES_MAXIMO
    FROM DBA_DATA_FILES
    GROUP BY TABLESPACE_NAME
),
TEMPFILES AS (
    SELECT TABLESPACE_NAME,
           SUM(BYTES) AS BYTES_TOTAL,
           SUM(CASE WHEN AUTOEXTENSIBLE = 'YES'
                    THEN GREATEST(BYTES, MAXBYTES) ELSE BYTES END) AS BYTES_MAXIMO
    FROM DBA_TEMP_FILES
    GROUP BY TABLESPACE_NAME
),
ESPACIO_LIBRE AS (
    SELECT TABLESPACE_NAME, SUM(BYTES) AS BYTES_LIBRES
    FROM DBA_FREE_SPACE
    GROUP BY TABLESPACE_NAME
),
ESPACIO_TEMPORAL AS (
    SELECT TABLESPACE_NAME, SUM(BYTES_USED) AS BYTES_USADOS
    FROM V$TEMP_SPACE_HEADER
    WHERE CON_ID = TO_NUMBER(SYS_CONTEXT('USERENV', 'CON_ID'))
    GROUP BY TABLESPACE_NAME
),
TABLESPACES AS (
    SELECT T.TABLESPACE_NAME, T.CONTENTS, T.STATUS,
           T.EXTENT_MANAGEMENT, T.SEGMENT_SPACE_MANAGEMENT,
           CASE WHEN T.CONTENTS = 'TEMPORARY'
                THEN TF.BYTES_TOTAL ELSE DF.BYTES_TOTAL END AS BYTES_TOTAL,
           CASE WHEN T.CONTENTS = 'TEMPORARY'
                THEN TF.BYTES_MAXIMO ELSE DF.BYTES_MAXIMO END AS BYTES_MAXIMO,
           NVL(EL.BYTES_LIBRES, 0) AS BYTES_LIBRES_PERMANENTES,
           NVL(ET.BYTES_USADOS, 0) AS BYTES_USADOS_TEMPORALES
    FROM DBA_TABLESPACES T
    LEFT JOIN DATAFILES DF ON DF.TABLESPACE_NAME = T.TABLESPACE_NAME
    LEFT JOIN TEMPFILES TF ON TF.TABLESPACE_NAME = T.TABLESPACE_NAME
    LEFT JOIN ESPACIO_LIBRE EL ON EL.TABLESPACE_NAME = T.TABLESPACE_NAME
    LEFT JOIN ESPACIO_TEMPORAL ET ON ET.TABLESPACE_NAME = T.TABLESPACE_NAME
),
OCUPACION AS (
    SELECT T.TABLESPACE_NAME, T.CONTENTS, T.STATUS,
           T.EXTENT_MANAGEMENT, T.SEGMENT_SPACE_MANAGEMENT,
           T.BYTES_TOTAL, T.BYTES_MAXIMO,
           CASE
               WHEN T.BYTES_TOTAL IS NULL OR T.STATUS = 'OFFLINE' THEN NULL
               WHEN T.CONTENTS = 'TEMPORARY' THEN T.BYTES_USADOS_TEMPORALES
               ELSE T.BYTES_TOTAL - T.BYTES_LIBRES_PERMANENTES
           END AS BYTES_USADOS,
           CASE
               WHEN T.BYTES_TOTAL IS NULL OR T.STATUS = 'OFFLINE' THEN NULL
               WHEN T.CONTENTS = 'TEMPORARY' THEN T.BYTES_TOTAL - T.BYTES_USADOS_TEMPORALES
               ELSE T.BYTES_LIBRES_PERMANENTES
           END AS BYTES_LIBRES
    FROM TABLESPACES T
),
R AS (
    SELECT COUNT(*) AS CANTIDAD_TABLESPACES,
           SUM(CASE WHEN CONTENTS != 'TEMPORARY' THEN BYTES_TOTAL ELSE 0 END) AS BYTES_DATAFILES,
           SUM(CASE WHEN CONTENTS = 'TEMPORARY' THEN BYTES_TOTAL ELSE 0 END) AS BYTES_TEMPFILES,
           CASE WHEN COUNT(*) = COUNT(BYTES_TOTAL) THEN SUM(BYTES_TOTAL) END AS BYTES_TOTAL,
           CASE WHEN COUNT(*) = COUNT(CASE WHEN BYTES_TOTAL >= 0 AND BYTES_USADOS >= 0
                     AND BYTES_LIBRES >= 0 AND BYTES_TOTAL = BYTES_USADOS + BYTES_LIBRES THEN 1 END)
                THEN SUM(BYTES_USADOS) END AS BYTES_USADOS,
           CASE WHEN COUNT(*) = COUNT(CASE WHEN BYTES_TOTAL >= 0 AND BYTES_USADOS >= 0
                     AND BYTES_LIBRES >= 0 AND BYTES_TOTAL = BYTES_USADOS + BYTES_LIBRES THEN 1 END)
                THEN SUM(BYTES_LIBRES) END AS BYTES_LIBRES
    FROM OCUPACION
)
SELECT D.DBID, C.DBID AS CON_DBID, C.CON_ID, I.INSTANCE_NAME,
       SYS_CONTEXT('USERENV', 'SERVICE_NAME') AS SERVICE_NAME, C.NAME AS CON_NAME,
       R.BYTES_DATAFILES, R.BYTES_TEMPFILES, R.BYTES_TOTAL, R.BYTES_USADOS, R.BYTES_LIBRES,
       R.CANTIDAD_TABLESPACES,
       (SELECT COUNT(*) FROM DBA_DATA_FILES) + (SELECT COUNT(*) FROM DBA_TEMP_FILES) AS CANTIDAD_ARCHIVOS
FROM R CROSS JOIN V$DATABASE D CROSS JOIN V$INSTANCE I CROSS JOIN V$CONTAINERS C
WHERE C.CON_ID = TO_NUMBER(SYS_CONTEXT('USERENV', 'CON_ID'));

CREATE OR REPLACE PROCEDURE SP_REGISTRAR_CRECIMIENTO(P_ID OUT NUMBER) AS
    V_DBID NUMBER;
    V_CON_DBID NUMBER;
    V_CON_ID NUMBER;
    V_INSTANCE_NAME VARCHAR2(128);
    V_SERVICE_NAME VARCHAR2(256);
    V_CON_NAME VARCHAR2(128);
    V_BYTES_DATAFILES NUMBER;
    V_BYTES_TEMPFILES NUMBER;
    V_BYTES_TOTAL NUMBER;
    V_BYTES_USADOS NUMBER;
    V_BYTES_LIBRES NUMBER;
    V_CANTIDAD_TABLESPACES NUMBER;
    V_CANTIDAD_ARCHIVOS NUMBER;
BEGIN
    SELECT DBID, CON_DBID, CON_ID, INSTANCE_NAME, SERVICE_NAME, CON_NAME,
           BYTES_DATAFILES, BYTES_TEMPFILES, BYTES_TOTAL, BYTES_USADOS, BYTES_LIBRES,
           CANTIDAD_TABLESPACES, CANTIDAD_ARCHIVOS
    INTO V_DBID, V_CON_DBID, V_CON_ID, V_INSTANCE_NAME, V_SERVICE_NAME, V_CON_NAME,
         V_BYTES_DATAFILES, V_BYTES_TEMPFILES, V_BYTES_TOTAL, V_BYTES_USADOS, V_BYTES_LIBRES,
         V_CANTIDAD_TABLESPACES, V_CANTIDAD_ARCHIVOS
    FROM V_ALMACENAMIENTO_ACTUAL;
    IF V_DBID IS NULL OR V_CON_DBID IS NULL OR V_CON_ID IS NULL
       OR V_INSTANCE_NAME IS NULL OR V_CON_NAME IS NULL
       OR V_CANTIDAD_TABLESPACES = 0
       OR V_BYTES_TOTAL IS NULL OR V_BYTES_USADOS IS NULL OR V_BYTES_LIBRES IS NULL
       OR V_BYTES_TOTAL < 0 OR V_BYTES_USADOS < 0 OR V_BYTES_LIBRES < 0
       OR V_BYTES_TOTAL != V_BYTES_USADOS + V_BYTES_LIBRES THEN
        RAISE_APPLICATION_ERROR(-20001, 'Medición incompleta o inconsistente; no se guardó historial.');
    END IF;
    INSERT INTO HISTORIAL_CRECIMIENTO_BD (
        DBID, CON_DBID, CON_ID, INSTANCE_NAME, SERVICE_NAME, CON_NAME, ALCANCE,
        BYTES_DATAFILES, BYTES_TEMPFILES, BYTES_USADOS, BYTES_LIBRES,
        CANTIDAD_TABLESPACES, CANTIDAD_ARCHIVOS)
    VALUES (
        V_DBID, V_CON_DBID, V_CON_ID, V_INSTANCE_NAME,
        V_SERVICE_NAME, V_CON_NAME, 'DATAFILES_TEMPFILES_V1',
        V_BYTES_DATAFILES, V_BYTES_TEMPFILES, V_BYTES_USADOS,
        V_BYTES_LIBRES, V_CANTIDAD_TABLESPACES, V_CANTIDAD_ARCHIVOS)
    RETURNING ID INTO P_ID;
    -- La transacción la confirma la aplicación o el job, nunca este procedimiento.
END;
/

CREATE OR REPLACE VIEW V_CRECIMIENTO_ANALITICO AS
SELECT H.ID, H.FECHA, H.DBID, H.CON_DBID, H.CON_ID, H.INSTANCE_NAME, H.SERVICE_NAME, H.CON_NAME,
       H.ALCANCE, H.BYTES_DATAFILES + H.BYTES_TEMPFILES AS BYTES_TOTAL,
       H.BYTES_USADOS, H.BYTES_LIBRES,
       ROUND((H.BYTES_DATAFILES + H.BYTES_TEMPFILES) / POWER(1024, 2), 2) AS TOTAL_MB,
       ROUND(H.BYTES_USADOS / POWER(1024, 2), 2) AS USADO_MB,
       ROUND(H.BYTES_LIBRES / POWER(1024, 2), 2) AS LIBRE_MB,
       ROUND((H.BYTES_USADOS - LAG(H.BYTES_USADOS) OVER (
           PARTITION BY H.DBID, H.CON_DBID, H.CON_ID, H.ALCANCE ORDER BY H.FECHA, H.ID))
           / POWER(1024, 2), 2) AS DELTA_MB,
       ROUND((H.BYTES_USADOS - LAG(H.BYTES_USADOS) OVER (
           PARTITION BY H.DBID, H.CON_DBID, H.CON_ID, H.ALCANCE ORDER BY H.FECHA, H.ID)) * 100
           / NULLIF(LAG(H.BYTES_USADOS) OVER (
           PARTITION BY H.DBID, H.CON_DBID, H.CON_ID, H.ALCANCE ORDER BY H.FECHA, H.ID), 0), 2)
           AS PORCENTAJE_CRECIMIENTO
FROM HISTORIAL_CRECIMIENTO_BD H
WHERE H.ALCANCE = 'DATAFILES_TEMPFILES_V1' AND H.DBID IS NOT NULL AND H.CON_DBID IS NOT NULL
  AND H.CON_ID IS NOT NULL AND H.INSTANCE_NAME IS NOT NULL AND H.CON_NAME IS NOT NULL
  AND H.BYTES_DATAFILES >= 0 AND H.BYTES_TEMPFILES >= 0
  AND H.BYTES_USADOS >= 0 AND H.BYTES_LIBRES >= 0
  AND H.BYTES_DATAFILES + H.BYTES_TEMPFILES = H.BYTES_USADOS + H.BYTES_LIBRES;
-- Los alias *_MB se conservan por compatibilidad; expresan MiB (1024^2 bytes).

-- Captura diaria opcional con el MISMO procedimiento y tabla. Se crea deshabilitada.
-- Si ya existe el job del script anterior, queda deshabilitado y se actualiza su acción.
-- La instalación debe dejar el job deshabilitado; no ejecutar ENABLE.
DECLARE
    V_EXISTE NUMBER;
    V_ACCION VARCHAR2(200) := 'DECLARE V_ID NUMBER; BEGIN SP_REGISTRAR_CRECIMIENTO(V_ID); COMMIT; END;';
BEGIN
    SELECT COUNT(*) INTO V_EXISTE FROM USER_SCHEDULER_JOBS
    WHERE JOB_NAME = 'JOB_HISTORIAL_ALMACENAMIENTO';
    IF V_EXISTE = 0 THEN
        DBMS_SCHEDULER.CREATE_JOB(
            job_name => 'JOB_HISTORIAL_ALMACENAMIENTO', job_type => 'PLSQL_BLOCK',
            job_action => V_ACCION, start_date => SYSTIMESTAMP,
            repeat_interval => 'FREQ=DAILY; BYHOUR=0; BYMINUTE=0; BYSECOND=0',
            enabled => FALSE, auto_drop => FALSE,
            comments => 'Módulo 3: captura del contenedor con identidad y alcance consistente');
    ELSE
        DBMS_SCHEDULER.DISABLE('JOB_HISTORIAL_ALMACENAMIENTO');
        DBMS_SCHEDULER.SET_ATTRIBUTE('JOB_HISTORIAL_ALMACENAMIENTO', 'job_action', V_ACCION);
    END IF;
END;
